"""Generate src/common/font_8x12.h: a 1-bit 8x12 bitmap font for printable ASCII (32..126).

Glyphs are rasterised from OpenCV's built-in Hershey font (public-domain stroke data), so the
header is reproducible: `py -3 tools/gen_font.py` from the stream-bench folder.
"""
import pathlib

import cv2
import numpy as np

W, H = 8, 12
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "common" / "font_8x12.h"


def glyph(ch: str) -> list[int]:
    big = np.zeros((H * 8, W * 8), np.uint8)
    (tw, th), _ = cv2.getTextSize(ch, cv2.FONT_HERSHEY_SIMPLEX, 2.9, 9)
    cv2.putText(big, ch, ((W * 8 - tw) // 2, 74), cv2.FONT_HERSHEY_SIMPLEX, 2.9, 255, 9, cv2.LINE_AA)
    small = cv2.resize(big, (W, H), interpolation=cv2.INTER_AREA)
    rows = []
    for y in range(H):
        bits = 0
        for x in range(W):
            if small[y, x] > 85:
                bits |= 0x80 >> x
        rows.append(bits)
    return rows


lines = [
    "// Generated by tools/gen_font.py (OpenCV Hershey simplex, rasterised). Do not edit.",
    "#pragma once",
    "#include <cstdint>",
    "namespace sb {",
    f"constexpr int kFontW = {W}, kFontH = {H};",
    f"static const uint8_t kFont8x12[95][{H}] = {{",
]
for code in range(32, 127):
    rows = glyph(chr(code))
    lines.append("  {" + ",".join(f"0x{r:02X}" for r in rows) + f"}},  // {chr(code)!r}")
lines += ["};", "}  // namespace sb", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print("wrote", OUT)
